/* CI step: turn a builder project (job/ folder, committed by htmlgames-worker)
   into the app's assets.
     job/build.json     { buildId, slug, dir, target, app:{name,package,versionName,versionCode,splashColor}, ads:{enabled,appId,interstitial,rewarded,banner} }
     job/config.json    the reskinned GAME_CONFIG
     job/icon.png       launcher icon (optional)
     job/files/**        uploaded art / sounds, at the path config.json refers to
   Output: app/src/main/assets/web/ (the game) + assets/app_settings.json + drawable/app_icon.png */
const fs = require("fs"), path = require("path");
const ROOT = path.join(__dirname, ".."), B = path.join(ROOT, "job");
const MAIN = path.join(ROOT, "app/src/main"), WEB = path.join(MAIN, "assets/web");
const job = JSON.parse(fs.readFileSync(path.join(B, "build.json"), "utf8"));
const config = JSON.parse(fs.readFileSync(path.join(B, "config.json"), "utf8"));

const safeDir = String(job.dir || "").replace(/[^a-z0-9_]/gi, "");
const src = path.join(ROOT, "games", safeDir);
if (!safeDir || !fs.existsSync(path.join(src, "index.html"))) throw new Error(`unknown game "${job.dir}"`);

function copyDir(from, to) {
  fs.mkdirSync(to, { recursive: true });
  for (const e of fs.readdirSync(from, { withFileTypes: true })) {
    if (e.name.startsWith(".") || e.name === "tools" || e.name.endsWith(".md")) continue;
    const s = path.join(from, e.name), d = path.join(to, e.name);
    e.isDirectory() ? copyDir(s, d) : fs.copyFileSync(s, d);
  }
}
fs.rmSync(WEB, { recursive: true, force: true });
copyDir(src, WEB);

// uploaded files: job/files/<path> → web/<path> (paths are confined to assets/)
const FILES = path.join(B, "files");
(function walk(dir, rel) {
  if (!fs.existsSync(dir)) return;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const r = rel ? `${rel}/${e.name}` : e.name;
    if (e.isDirectory()) walk(path.join(dir, e.name), r);
    else if (/^assets\/[\w\-./]+$/.test(r) && !r.includes("..")) {
      fs.mkdirSync(path.dirname(path.join(WEB, r)), { recursive: true });
      fs.copyFileSync(path.join(dir, e.name), path.join(WEB, r));
    }
  }
})(FILES, "");

// the reskinned config; ads go through the native bridge, never the simulator
config.ads = { ...(config.ads || {}), enabled: !!(job.ads && job.ads.enabled), simulate: false };
fs.writeFileSync(path.join(WEB, "js/config.js"),
  `/* ${job.app.name} — generated by the HTML Games Code builder (build ${job.buildId}) */\nwindow.GAME_CONFIG = ${JSON.stringify(config, null, 2)};\n`);

fs.writeFileSync(path.join(MAIN, "assets/app_settings.json"), JSON.stringify({
  appName: job.app.name, package: job.app.package, versionName: job.app.versionName, versionCode: job.app.versionCode,
  splashColor: job.app.splashColor, ads: job.ads
}, null, 2));

const icon = path.join(B, "icon.png");
if (fs.existsSync(icon)) fs.copyFileSync(icon, path.join(MAIN, "res/drawable/app_icon.png"));
console.log(`prepared ${job.slug} as ${job.app.package} v${job.app.versionName} (${job.app.versionCode}), target ${job.target}`);
