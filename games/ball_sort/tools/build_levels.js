/* Builds js/levels.js: every level is generated with a fixed seed and
   verified solvable by the A* solver before it is written out.
   Usage: node tools/build_levels.js [count=500] [seedBase=7331] */
const fs = require("fs"), path = require("path");
const E = require("../js/engine.js");
const count = +(process.argv[2] || 500), seedBase = +(process.argv[3] || 7331);

// Hand-made openers (tutorial). Format matches Engine.encode.
const PINNED = {
  1: "aabb|bbaa|;3;6;"            // pour, pour, pour — teaches the rule
};

const out = [];
let t0 = Date.now();
for (let n = 1; n <= count; n++) {
  if (PINNED[n]) {
    const L = E.decode(PINNED[n]);
    const sol = E.solve(L.tubes, L.cap, { weight: 1 });
    if (!sol) throw new Error("pinned level " + n + " is unsolvable");
    L.par = sol.length; L.parBalls = sol.reduce((s, m) => s + m[2], 0);
    out.push(E.encode(L)); continue;
  }
  const sp = E.spec(n);
  let L = null;
  for (let k = 0; !L && k < 20; k++) L = E.generate(sp, seedBase + n * 7919 + k * 104729);
  if (!L) throw new Error("could not generate level " + n);
  // double-check: replay the solution on a copy
  const sol = E.solve(L.tubes, L.cap);
  const copy = L.tubes.map(t => t.slice());
  sol.forEach(([a, b]) => E.move(copy, L.cap, a, b));
  if (!E.isSolved(copy, L.cap)) throw new Error("solution replay failed on level " + n);
  out.push(E.encode(L));
}
const body = `/* AUTO-GENERATED by tools/build_levels.js — ${count} solver-verified levels.
   Format: tubes (a–l = colors, bottom→top) ; par pours ; par single-ball moves ; flags (h = hard, m = mystery) */
window.LEVELS = ${JSON.stringify(out, null, 0).replace(/","/g, '",\n"')};
`;
fs.writeFileSync(path.join(__dirname, "../js/levels.js"), body);
const flags = out.reduce((s, l) => { const f = l.split(";")[3]; if (f.includes("h")) s.h++; if (f.includes("m")) s.m++; return s; }, { h: 0, m: 0 });
console.log(`wrote ${count} levels (${flags.h} hard, ${flags.m} mystery) in ${Date.now() - t0}ms`);
