#!/usr/bin/env node
/* ==========================================================================
   CSV → js/questions.js
   Manage questions in Google Sheets / Excel, export as CSV, then run:

     node tools/csv_to_questions.js tools/questions_template.csv
     node tools/csv_to_questions.js my.csv --json questions.json   # for config.questionsUrl

   Columns (header row required):
     category, difficulty, question, correct, wrong1, wrong2, wrong3
   • True/false: put TRUE or FALSE in "correct" and leave the wrong columns empty.
   • category must match an id in config.js (science, geography, …) or add a new one there.
   • difficulty: 1 easy · 2 medium · 3 hard
   ========================================================================== */
const fs = require("fs");
const path = require("path");

const file = process.argv[2];
if (!file) { console.error("Usage: node tools/csv_to_questions.js <file.csv> [--json out.json]"); process.exit(1); }
const jsonOut = process.argv.includes("--json") ? process.argv[process.argv.indexOf("--json") + 1] : null;

// RFC 4180-ish parser: quoted fields, escaped quotes, commas/newlines inside quotes
function parseCSV(text) {
  const rows = []; let row = [], field = "", q = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (q) {
      if (ch === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (ch === '"') q = false;
      else field += ch;
    } else if (ch === '"') q = true;
    else if (ch === ",") { row.push(field); field = ""; }
    else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(field); rows.push(row); row = []; field = "";
    } else field += ch;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows.filter(r => r.some(c => c.trim()));
}

const rows = parseCSV(fs.readFileSync(file, "utf8").replace(/^﻿/, ""));
const header = rows.shift().map(h => h.trim().toLowerCase());
const col = name => header.indexOf(name);
const need = ["category", "difficulty", "question", "correct"];
need.forEach(n => { if (col(n) < 0) { console.error(`Missing column: ${n}`); process.exit(1); } });

const out = [], problems = [];
rows.forEach((r, i) => {
  const get = n => (col(n) >= 0 ? (r[col(n)] || "").trim() : "");
  const line = i + 2;
  const cat = get("category").toLowerCase(), d = Math.max(1, Math.min(3, parseInt(get("difficulty"), 10) || 1));
  const q = get("question"), correct = get("correct");
  if (!cat || !q || !correct) return problems.push(`line ${line}: missing category/question/correct`);
  const wrong = ["wrong1", "wrong2", "wrong3"].map(get).filter(Boolean);
  if (/^(true|false)$/i.test(correct) && !wrong.length) out.push([cat, d, q, correct.toLowerCase() === "true"]);
  else if (wrong.length === 3) {
    if (wrong.some(w => w.toLowerCase() === correct.toLowerCase())) problems.push(`line ${line}: a wrong answer repeats the correct one`);
    out.push([cat, d, q, correct, ...wrong]);
  } else problems.push(`line ${line}: multiple choice needs exactly 3 wrong answers (got ${wrong.length})`);
});

if (problems.length) { console.error("Problems:\n  " + problems.join("\n  ")); }
if (jsonOut) {
  fs.writeFileSync(jsonOut, JSON.stringify(out));
  console.log(`Wrote ${out.length} questions to ${jsonOut}`);
} else {
  const dest = path.join(__dirname, "..", "js", "questions.js");
  const body = out.map(r => "  " + JSON.stringify(r).replace(/","/g, '", "').replace(/,(\d|true|false)/g, ", $1")).join(",\n");
  fs.writeFileSync(dest, `/* Generated by tools/csv_to_questions.js from ${path.basename(file)}.\n   [category, difficulty, question, CORRECT, wrong, wrong, wrong] or [category, difficulty, question, true|false] */\nwindow.QUESTIONS = [\n${body}\n];\n`);
  console.log(`Wrote ${out.length} questions to js/questions.js`);
}
const cats = {}; out.forEach(r => { cats[r[0]] = (cats[r[0]] || 0) + 1; });
console.log("Per category:", cats);
