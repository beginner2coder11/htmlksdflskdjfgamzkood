/* Generates js/levels.js: sliding-block puzzles on a 6×6 board, each solved by BFS so the minimum
   number of moves is exact. Block 0 is the red crate (horizontal, row 2) and must reach the exit
   on the right. Run: node tools/gen.js [count] */
const fs = require("fs"), path = require("path");
const N = 6, ROW = 2, COUNT = +process.argv[2] || 60;
let seed = 20261104; const rnd = () => (seed = (seed * 48271) % 2147483647) / 2147483647;

function occupied(blocks, skip = -1) { const g = new Array(N * N).fill(-1); blocks.forEach((b, i) => { if (i === skip) return; for (let k = 0; k < b.len; k++) g[(b.r + (b.h ? 0 : k)) * N + b.c + (b.h ? k : 0)] = i; }); return g; }
const key = bs => bs.map(b => b.h ? b.c : b.r).join(",");
function moves(bs) {
  const g = occupied(bs), out = [];
  bs.forEach((b, i) => {
    for (const d of [-1, 1]) for (let s = 1; s < N; s++) {
      const nb = { ...b }; if (b.h) nb.c += d * s; else nb.r += d * s;
      const lo = b.h ? nb.c : nb.r; if (lo < 0 || lo + b.len > N) break;
      const cell = b.h ? b.r * N + (d > 0 ? nb.c + b.len - 1 : nb.c) : (d > 0 ? nb.r + b.len - 1 : nb.r) * N + b.c;
      if (g[cell] !== -1 && g[cell] !== i) break;
      out.push([i, d * s]);
    }
  });
  return out;
}
function apply(bs, [i, d]) { const n = bs.map(b => ({ ...b })); if (n[i].h) n[i].c += d; else n[i].r += d; return n; }
function solve(bs, cap = 400000) {
  const start = key(bs), seen = new Map([[start, null]]), q = [bs]; let qi = 0;
  while (qi < q.length) {
    const s = q[qi++]; if (s[0].c === N - 2) { let len = 0, k = key(s); while (seen.get(k)) { len++; k = seen.get(k)[0]; } return { len, states: seen.size }; }
    if (seen.size > cap) return null;
    for (const m of moves(s)) { const n = apply(s, m), k = key(n); if (!seen.has(k)) { seen.set(k, [key(s), m]); q.push(n); } }
  }
  return { len: -1 };
}
function random() {
  const bs = [{ r: ROW, c: Math.floor(rnd() * 2), len: 2, h: true }], want = 8 + Math.floor(rnd() * 6);
  let tries = 0;
  while (bs.length < want && tries++ < 300) {
    const h = rnd() < 0.5, len = rnd() < 0.3 ? 3 : 2, b = { h, len, r: Math.floor(rnd() * (h ? N : N - len + 1)), c: Math.floor(rnd() * (h ? N - len + 1 : N)) };
    if (h && b.r === ROW) continue;                // no other horizontal block on the exit row
    const g = occupied(bs); let ok = true; for (let k = 0; k < len; k++) if (g[(b.r + (h ? 0 : k)) * N + b.c + (h ? k : 0)] !== -1) ok = false;
    if (ok) bs.push(b);
  }
  return bs;
}
const found = [], seenKeys = new Set(), t0 = Date.now();
const buckets = [[3, 6], [6, 10], [10, 15], [15, 22], [22, 60]], per = Math.ceil(COUNT / buckets.length);
for (const [lo, hi] of buckets) {
  let got = 0, attempts = 0;
  while (got < per && attempts++ < 60000) {
    const bs = random(), k = bs.map(b => `${b.r}${b.c}${b.len}${b.h ? 1 : 0}`).sort().join(""); if (seenKeys.has(k)) continue;
    const s = solve(bs); if (!s || s.len < lo || s.len >= hi) continue;
    seenKeys.add(k); found.push({ min: s.len, blocks: bs.map(b => [b.r, b.c, b.len, b.h ? 1 : 0]) }); got++;
  }
  console.log(`moves ${lo}-${hi - 1}: ${got} puzzles (${attempts} attempts)`);
}
found.sort((a, b) => a.min - b.min);
const out = "/* Generated by tools/gen.js — each level: min = exact minimum moves, blocks = [row, col, length, horizontal]. Block 0 is the red crate. */\nwindow.LEVELS = " + JSON.stringify(found.slice(0, COUNT)) + ";\n";
fs.writeFileSync(path.join(__dirname, "../js/levels.js"), out);
console.log(`wrote ${Math.min(COUNT, found.length)} levels in ${((Date.now() - t0) / 1000).toFixed(1)}s, hardest ${found[found.length - 1].min} moves`);
